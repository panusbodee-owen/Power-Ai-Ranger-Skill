# -*- coding: utf-8 -*-
"""Research แบบ 'เริ่มจากปัญหา': ค้นสัญญาณความเจ็บปวดของ SME ไทยแยกกลุ่มธุรกิจ -> ทีมสกัดปัญหาพร้อมหลักฐาน -> บรรณาธิการจัดลำดับตามความแข็งของหลักฐาน
-> ผู้เลือกคัด 3 ปัญหา/ไอเดียธุรกิจ -> ค้นคู่แข่ง/ราคา/ทางเลือกที่ลูกค้าใช้อยู่ -> ผู้วิเคราะห์ตรวจความเป็นไปได้ + การทดลอง 2 สัปดาห์
ไม่ให้คะแนนตัวเลข (ครั้งก่อนเป็นการบวกคะแนนเดา) ใช้ 'ความแข็งของหลักฐาน' แทน: แข็ง = ≥2 แหล่งอิสระและมีเว็บราชการ/สื่อ, กลาง = ≥2 แหล่งแต่เป็นสื่อ/บล็อก, อ่อน = โซเชียลหรือแหล่งเดียว"""
import io, time
import team, webtools
from researchteam import CONTEXT, _result

SEGMENTS = [
    ("ร้านค้าปลีก/ร้านชำ/โชห่วย", "ปัญหา ร้านค้าปลีก ร้านชำ SME ไทย เงินสด สต็อก ต้นทุน ขาดทุน"),
    ("ผู้ขายออนไลน์ (Shopee/Lazada/TikTok/LINE)", "ปัญหา พ่อค้าแม่ค้าออนไลน์ ไทย ต้นทุน ค่าธรรมเนียม ทำบัญชี จัดการออเดอร์"),
    ("ร้านอาหาร/คาเฟ่", "ปัญหา ร้านอาหาร SME ไทย ต้นทุนวัตถุดิบ พนักงาน กำไรน้อย ระบบ POS"),
    ("ผู้รับเหมา/วัสดุก่อสร้าง/ค้าส่ง", "ปัญหา ผู้รับเหมา ร้านวัสดุก่อสร้าง SME ไทย ลูกหนี้ เก็บเงิน เครดิต ใบเสนอราคา"),
    ("โรงงาน/ผู้ผลิตขนาดเล็ก", "ปัญหา โรงงานขนาดเล็ก SME ผู้ผลิต ไทย ต้นทุน สต็อก วางแผนผลิต ระบบ ERP"),
    ("ขนส่ง/โลจิสติกส์/รถบรรทุก", "ปัญหา ธุรกิจขนส่ง รถบรรทุก SME ไทย ค่าน้ำมัน บริหารรถ เก็บเงิน"),
    ("เกษตร/แปรรูปอาหาร", "ปัญหา เกษตรกร ผู้แปรรูปอาหาร SME ไทย ต้นทุน ตลาด มาตรฐาน ค่าใช้จ่าย"),
    ("ธุรกิจบริการ/คลินิก/ความงาม/ฟรีแลนซ์", "ปัญหา ธุรกิจบริการ คลินิก ร้านเสริมสวย SME ไทย นัดหมาย ลูกค้าหาย ระบบสมาชิก"),
    ("SME ทั่วไป: เงินทุน/บัญชี/ภาษี/กฎหมายใหม่", "SME ไทย ปัญหา สภาพคล่อง ภาษี e-Tax Invoice ใบกำกับภาษีอิเล็กทรอนิกส์ บัญชี กฎหมายใหม่ 2569"),
]


def run(topic, out, name=None):
    c = team.db()
    name = name or "research-pf-" + time.strftime("%m%d-%H%M")
    packs = []
    for seg, q in SEGMENTS:                          # ขั้น 1: ค้นสัญญาณปัญหาแยกกลุ่ม (โค้ด)
        try:
            packs.append(webtools.fact_pack(q, 6, 2)[:9000])
        except Exception as e:
            packs.append(f"(ค้นเว็บไม่สำเร็จ: {e})")
        time.sleep(13)
    tids = []
    for (seg, q), pack in zip(SEGMENTS, packs):      # ขั้น 2: สกัดปัญหาพร้อมหลักฐาน ขนาน
        brief = (f"{pack}\n\n=====\n{CONTEXT}\n\nงาน (ผู้วิเคราะห์): กลุ่มธุรกิจ \"{seg}\" จากหลักฐานข้างบนเท่านั้น สกัดปัญหาที่ SME กลุ่มนี้เจอจริง 2-3 ข้อ ไม่เกิน 180 คำ ภาษาไทย "
                 "แต่ละข้อบอก: ปัญหาคืออะไร ใครเจ็บ มีหลักฐานชนิดใด [W#] (ระบุว่าเป็นเว็บราชการ/สื่อ/บล็อก/โซเชียล) และตอนนี้เขาแก้ปัญหานี้ด้วยอะไร "
                 "ถ้าหลักฐานไม่พอให้เขียน 'หลักฐานอ่อน' ห้ามแต่งปัญหาหรือตัวเลขที่ไม่อยู่ในหลักฐาน ห้ามเสนอผลิตภัณฑ์ ให้พูดเฉพาะปัญหา")
        tids.append(team.submit(c, brief, "@auto", f"{name}-problems", None, None, 0, "analyst"))
    team.worker(8, 3, drain=True)
    probs = []
    for (seg, q), tid in zip(SEGMENTS, tids):
        st, res, seat, err = _result(c, tid)
        if st == "done" and (res or "").strip():
            probs.append((seg, res.strip()))
    if len(probs) < 4:
        raise ValueError("สกัดปัญหาสำเร็จน้อยกว่า 4 กลุ่ม — รันใหม่ได้")
    body = "\n\n".join(f"### {s}\n{r}" for s, r in probs)
    rule = ("เกณฑ์ความแข็งของหลักฐาน: แข็ง = ≥2 แหล่งอิสระและมีเว็บราชการหรือสื่อ; กลาง = ≥2 แหล่งแต่เป็นสื่อ/บล็อก; อ่อน = โซเชียลหรือแหล่งเดียว ห้ามให้คะแนนตัวเลข")
    # ขั้น 3a: บรรณาธิการจัดลำดับปัญหา (ผู้ตรวจ seat5)   ขั้น 3b: ผู้เลือกคัด 3 ไอเดียเป็น JSON พร้อมกัน
    b_edit = (f"ปัญหาที่สกัดได้ต่อกลุ่มธุรกิจ (ข้อมูลอ้างอิง):\n\n{body}\n\n=====\n{CONTEXT}\n\n{rule}\n"
              "งาน (บรรณาธิการ): จากข้อมูลข้างบนเท่านั้น เขียนไม่เกิน 450 คำ ภาษาไทย: (1) ตารางปัญหาเรียงตามความแข็งของหลักฐาน: ปัญหา | กลุ่ม | ความแข็งของหลักฐาน | แหล่งที่ใช้ "
              "(2) ปัญหาที่เกิดซ้ำข้ามหลายกลุ่ม (3) ปัญหาที่หลักฐานอ่อนแต่น่าตรวจ ห้ามเพิ่มข้อเท็จจริงหรือตัวเลขใหม่ ห้ามเสนอผลิตภัณฑ์")
    t_edit = team.submit(c, b_edit, None, f"{name}-rank", None, team.parse_flow("editor@@auto>reviewer@seat5"), 1)
    b_pick = (f"ปัญหาที่สกัดได้ต่อกลุ่มธุรกิจ:\n\n{body}\n\n=====\n{CONTEXT}\n\n{rule}\n"
              "งาน (ผู้วิเคราะห์): เลือก 3 ปัญหาที่หลักฐานแข็งที่สุดและเหมาะกับผู้ก่อตั้งคนเดียวมากที่สุด แล้วเสนอแต่ละอย่างเป็นไอเดียธุรกิจ 1 ประโยค "
              'ตอบเป็น JSON เท่านั้น: {"ideas":[{"problem":"ปัญหา","segment":"กลุ่ม","business":"ไอเดียธุรกิจ 1 ประโยค","query":"คำค้นภาษาไทยเพื่อหาคู่แข่ง/ราคา/ทางเลือกที่มีอยู่"}]}')
    t_pick = team.submit(c, b_pick, "@auto", f"{name}-pick", "json", None, 0, "analyst")
    team.worker(8, 3, drain=True)
    st_e, res_e, seat_e, err_e = _result(c, t_edit)
    st_p, res_p, _, _ = _result(c, t_pick)
    data = team.first_json(res_p or "") if res_p else None
    ideas = [x for x in ((data or {}).get("ideas") or []) if isinstance(x, dict) and x.get("business") and x.get("query")][:3] if isinstance(data, dict) else []
    if not ideas:
        raise ValueError(f"ผู้เลือกไม่ได้ส่ง JSON ไอเดีย ({st_p}) — รันใหม่ได้")
    ev, t3 = [], []
    for it in ideas:                                  # ขั้น 4: ค้นคู่แข่ง/ราคา/ทางเลือก
        try:
            ev.append(webtools.fact_pack(it["query"], 6, 2)[:9000])
        except Exception as e:
            ev.append(f"(ค้นเว็บไม่สำเร็จ: {e})")
        time.sleep(13)
    for it, pack in zip(ideas, ev):
        brief = (f"{pack}\n\n=====\n{CONTEXT}\n\nงาน (ผู้วิเคราะห์): ไอเดีย \"{it['business']}\" แก้ปัญหา \"{it['problem']}\" (กลุ่ม {it.get('segment', '')}) "
                 "จากหลักฐานข้างบนเท่านั้น ไม่เกิน 260 คำ ภาษาไทย: (1) ลูกค้าใช้อะไรแก้ปัญหานี้อยู่ตอนนี้ และคู่แข่ง/ทางเลือกที่เห็นในหลักฐาน (ชื่อ + ราคาเฉพาะที่ปรากฏ [W#]) "
                 "(2) ช่องว่างที่ยังไม่มีใครตอบ (3) ความเสี่ยงสำหรับผู้ก่อตั้งคนเดียว (กฎหมาย, non-compete กับ Odoo, ภาระ support) "
                 "(4) การทดลอง 2 สัปดาห์ที่ไม่ใช้เงินโฆษณา พร้อมเกณฑ์ผ่าน/ไม่ผ่านที่เป็นตัวเลขเป้าหมายการทดลอง (ไม่ใช่ตัวเลขตลาด) "
                 "(5) สิ่งที่ยังเป็น [สมมติ] ห้ามแต่งตัวเลขตลาด/ราคาที่ไม่อยู่ในหลักฐาน")
        t3.append(team.submit(c, brief, "@auto", f"{name}-validate", None, None, 0, "analyst"))
    team.worker(8, 3, drain=True)
    L = [f"# ทีม Research (เริ่มจากปัญหา): {topic}", "",
         f"> ค้นเว็บจริง (TinySearch) {len(SEGMENTS)} กลุ่มธุรกิจ + {len(ideas)} ไอเดีย · บรรณาธิการ ช่อง {seat_e} · สถานะตรวจการจัดลำดับ: {st_e}",
         "> ไม่มีคะแนนตัวเลข ใช้ 'ความแข็งของหลักฐาน' แทน ข้อความที่ไม่มีหลักฐานติด [สมมติ] — ไม่ใช่ข้อสรุปให้ลงทุน ต้องตรวจจริงตามการทดลอง 2 สัปดาห์", "",
         "## 1) ปัญหาของ SME ไทยที่พบ เรียงตามความแข็งของหลักฐาน", "", (res_e or f"(บรรณาธิการไม่สำเร็จ: {st_e} {err_e})").strip(), "", "---", "",
         "## 2) ไอเดียธุรกิจ 3 ทางที่คัดจากปัญหา พร้อมตรวจคู่แข่งและการทดลอง", ""]
    for it, tid in zip(ideas, t3):
        st, res, seat, err = _result(c, tid)
        L += [f"### {it['business']}", f"*แก้ปัญหา: {it['problem']} · กลุ่ม: {it.get('segment', '')} · ผู้ประเมิน: {seat or '-'} · {st}*", "", (res or f"(ไม่สำเร็จ: {err})").strip(), ""]
    L += ["---", "", "## 3) ปัญหาดิบรายกลุ่มธุรกิจ (ที่ทีมสกัดจากหลักฐาน)", ""]
    for s, r in probs:
        L += [f"### {s}", r, ""]
    L += ["---", "", "## 4) หลักฐานที่ค้นมา (แหล่งอ้างอิง ตัดตอน)", ""]
    for (s, q), pack in zip(SEGMENTS, packs):
        L += [f"### {s}", "```", pack[:3500], "```", ""]
    for it, pack in zip(ideas, ev):
        L += [f"### คู่แข่ง: {it['business']}", "```", pack[:3500], "```", ""]
    io.open(out, "w", encoding="utf-8").write("\n".join(L))
    return st_e, name, out
